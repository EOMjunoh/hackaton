  async function fetchKmaShortTerm(sido, sigun){
    const g = sido ? getGrid(sido, sigun) : getGridBySigun(sigun);
    if(!g) return null;
    try{
      const res=await fetch(`/api/weather?nx=${g.nx}&ny=${g.ny}`);
      const data=await res.json();
      if(!res.ok||!Array.isArray(data.days)||!data.days.length) return null;
      const byDate={};
      data.days.forEach(d=>{ byDate[d.date]=d; });
      const todayKst=new Date(Date.now()+9*60*60*1000);
      const byOffset={};
      for(let i=0;i<7;i++){
        const d=new Date(todayKst); d.setUTCDate(d.getUTCDate()+i);
        const key=`${d.getUTCFullYear()}${String(d.getUTCMonth()+1).padStart(2,'0')}${String(d.getUTCDate()).padStart(2,'0')}`;
        if(byDate[key]) byOffset[i]=byDate[key];
      }
      const offsets=Object.keys(byOffset).map(Number).sort((a,b)=>a-b);
      if(!offsets.length) return null;
      return{byOffset,offsets,grid:g};
    }catch(e){ return null; }
  }

